export const messages: Record<Lang, Record<MessageKey, string>> = { en, zh };

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

/** Picks a language from the Accept-Language header: Chinese if listed before English, else English. */
export function langFromAcceptLanguage(header: string | null | undefined): Lang {
  if (!header) return "en";
  for (const part of header.toLowerCase().split(",")) {
    const tag = part.trim().split(";")[0];
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const table = messages[lang];
  return (key, vars) =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => (vars && name in vars ? String(vars[name]) : `{${name}}`));
}

/** The messages whose keys start with any of the prefixes, for passing to client components. */
export function pickMessages(lang: Lang, prefixes: string[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(messages[lang])) {
    if (prefixes.some((p) => key.startsWith(p))) out[key] = value;
  }
  return out;
}
